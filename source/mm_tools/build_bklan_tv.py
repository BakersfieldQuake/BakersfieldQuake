"""bklan3 TVs: turn the owner's 8 clips (G:\\Downloads, 2026-10-31) into TV content for the map.
The engine has no video-in-world and caps a shader's animmap at 64 frames, so every clip is cut into chunks of STRIDE (62) new
frames (6.2 s at 10 fps); each chunk is one 64-frame shader (scripts/bktv.shader, bktv_cNN; its last two frames are the next
chunk's first two) and one skin of progs/bk_tvscr.md3. QC (bklan_tv.qc) spawns a new screen entity with the next chunk's skin
every 6.2 s, because an animmap's clock starts when the client first gets the entity. The two spare frames let that happen
up to 0.2 s late without a jump.
Writes: progs/bktv/v<N>_<frame>.jpg, scripts/bktv.shader, sound/bklan/tv_<N>.wav, progs/bk_tvscr.md3 (+ _<skin>.skin),
source/mm_tools/bklan_tv_data.qc (clip table, generated).
usage: python build_bklan_tv.py   (WindowsApps python3.13; needs ffmpeg on PATH; env BKTV_TEST=1 burns frame numbers in)"""
import json
import os
import subprocess
import sys

import md3lib

HERE = os.path.dirname(os.path.abspath(__file__))
MOD = os.path.abspath(os.path.join(HERE, "..", ".."))
DL = r"G:\Downloads"
CLIPS = [
    "grok-video-685f8cf0-eee0-4435-92d3-c6092ef0bab9 (1).mp4",
    "grok-video-18f4eae4-915d-4bec-bfaf-c1a16d4de09e.mp4",
    "grok-video-4251788a-dc94-496d-930d-be35a5be1277 (3).mp4",
    "character_showcase.mp4",
    "grok-video-20a5f777-3186-41bc-b38e-5c5881690bc4 (1).mp4",
    "02177798374183100000000000000000000ffffc0a87905c7e0dd.mp4",
    "grok-video-80a3dc6d-1632-4f35-bbf9-e3370c7a94eb.mp4",
    "grok-video-0454d933-6ecd-468f-b97c-f7fba5afb590.mp4",
]
W, H = 160, 120
FPS = 10
CHUNK = 64                # frames in a shader
STRIDE = 62               # new frames per chunk (the last two of a shader are the next chunk's first two)
BRIGHT = float(os.environ.get("BKTV_BRIGHT", "0.55"))     # the scene is lit x2.5: bake the picture down
TEST = os.environ.get("BKTV_TEST") == "1"


def ffprobe_dur(path):
    out = subprocess.check_output(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", path])
    return float(out.decode().strip())


def main():
    fdir = os.path.join(MOD, "progs", "bktv")
    os.makedirs(fdir, exist_ok=True)
    os.makedirs(os.path.join(MOD, "sound", "bklan"), exist_ok=True)
    for f in os.listdir(fdir):
        os.remove(os.path.join(fdir, f))
    vids = []
    for v, name in enumerate(CLIPS):
        src = os.path.join(DL, name)
        dur = ffprobe_dur(src)
        vf = ("fps=%d,scale=%d:%d:force_original_aspect_ratio=decrease,pad=%d:%d:(ow-iw)/2:(oh-ih)/2:black,"
              "eq=brightness=0:contrast=1,lutrgb=r=val*%.3f:g=val*%.3f:b=val*%.3f") % (FPS, W, H, W, H, BRIGHT, BRIGHT, BRIGHT)
        if TEST:
            vf += r",drawtext=fontfile='C\:/Windows/Fonts/arial.ttf':text='%{n}':x=4:y=4:fontsize=40:fontcolor=white:box=1:boxcolor=black"
        subprocess.check_call(["ffmpeg", "-v", "error", "-y", "-i", src, "-an", "-vf", vf, "-q:v", "4", "-start_number", "0",
                               os.path.join(fdir, "v%d_%%04d.jpg" % v)])
        n = len([f for f in os.listdir(fdir) if f.startswith("v%d_" % v)])
        subprocess.check_call(["ffmpeg", "-v", "error", "-y", "-i", src, "-vn", "-ac", "1", "-ar", "22050", "-af",
                               "loudnorm=I=-20:TP=-3", "-c:a", "pcm_s16le",
                               os.path.join(MOD, "sound", "bklan", "tv_%d.wav" % v)])
        vids.append(dict(name=name, dur=dur, frames=n, chunks=(n + STRIDE - 1) // STRIDE))
        print("clip %d: %d frames, %d chunks, %.1f s" % (v, n, vids[-1]["chunks"], dur))

    shaders = ["// generated by build_bklan_tv.py: one shader per 64-frame chunk of the TV clips\n"
               "progs/bktv_off\n{\n\tcull none\n\t{\n\t\tmap progs/bktv_off\n\t\trgbGen identity\n\t}\n}\n"]
    skin = 1
    table = []
    for v, vd in enumerate(vids):
        vd["first"] = skin
        n = vd["frames"]
        for j in range(vd["chunks"]):
            idx = [min(STRIDE * j + i, n - 1) for i in range(CHUNK)]
            names = " ".join("progs/bktv/v%d_%04d" % (v, k) for k in idx)
            shaders.append("progs/bktv_c%d\n{\n\tcull none\n\t{\n\t\tanimmap %d %s\n\t\trgbGen identity\n\t}\n}\n" % (skin, FPS, names))
            skin += 1
        table.append(vd)
    assert skin < 255
    with open(os.path.join(MOD, "scripts", "bktv.shader"), "w", newline="\n") as f:
        f.write("\n".join(shaders))
    # the "off" card: dark grey with a faint scan pattern
    subprocess.check_call(["ffmpeg", "-v", "error", "-y", "-f", "lavfi", "-i", "color=c=0x101418:s=%dx%d" % (W, H), "-frames:v", "1",
                           os.path.join(MOD, "progs", "bktv_off.png")])

    # the screen: a 48 x 36 unit quad facing +x, centred on its origin
    hw, hh = 24.0, 18.0
    vs = [(0.0, -hw, hh), (0.0, hw, hh), (0.0, hw, -hh), (0.0, -hw, -hh)]
    ns = [(1.0, 0.0, 0.0)] * 4
    st = [(0.0, 0.0), (1.0, 0.0), (1.0, 1.0), (0.0, 1.0)]
    surf = dict(name="bk_tvscr", shader="progs/bktv_off", tris=[(0, 1, 2), (0, 2, 3)], st=st, frames=[(vs, ns)])
    md3lib.write(os.path.join(MOD, "progs", "bk_tvscr.md3"), dict(name="bk_tvscr", surfaces=[surf], nframes=1))
    for k in range(skin):
        with open(os.path.join(MOD, "progs", "bk_tvscr.md3_%d.skin" % k), "w", newline="\n") as f:
            f.write("bk_tvscr,progs/bktv_%s\n" % ("off" if k == 0 else "c%d" % k))

    # QC table
    q = ["// generated by build_bklan_tv.py: the TV clips (skin of a clip's chunk j = first + j)\n",
         "float BKTV_CLIPS = %d;\n" % len(table), "float BKTV_CHUNK = %.1f;\t\t// seconds a chunk plays (%d new frames at %d fps)\n" % (STRIDE / FPS, STRIDE, FPS),
         "float(float v) BKTV_First =\n{\n"]
    q += ["\tif (v == %d) return %d;\n" % (v, d["first"]) for v, d in enumerate(table)]
    q += ["\treturn 1;\n};\n\nfloat(float v) BKTV_Chunks =\n{\n"]
    q += ["\tif (v == %d) return %d;\n" % (v, d["chunks"]) for v, d in enumerate(table)]
    q += ["\treturn 1;\n};\n\nstring(float v) BKTV_Sound =\n{\n"]
    q += ['\tif (v == %d) return "bklan/tv_%d.wav";\n' % (v, v) for v in range(len(table))]
    q += ['\treturn "bklan/tv_0.wav";\n};\n\nvoid() BKTV_Precache =\n{\n\tif (bktv_precached)\n\t\treturn;\n\tbktv_precached = TRUE;\n\tprecache_model ("progs/bk_tvscr.md3");\n']
    q += ['\tprecache_sound ("bklan/tv_%d.wav");\n' % v for v in range(len(table))]
    q += ["};\n"]
    with open(os.path.join(HERE, "bklan_tv_data.qc"), "w", newline="\n") as f:
        f.write("".join(q))
    json.dump(table, open(os.path.join(HERE, "out", "bklan_tv_clips.json"), "w"), indent=1)
    print("%d chunk shaders / skins, %d frames" % (skin - 1, sum(d["frames"] for d in table)))


if __name__ == "__main__":
    sys.exit(main())
