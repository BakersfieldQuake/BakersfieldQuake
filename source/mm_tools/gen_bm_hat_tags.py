"""Write source/qc_combat_decomp/bm_hat_tags.qc from the head-socket table in zz_hats.pk3.

The table gives, for each of the player model's animation frames, where the top of the head is
(position and rotation, in the player model's own axes). The QC holds it as Quake offsets and angles.

Usage: python -I source/mm_tools/gen_bm_hat_tags.py path/to/zz_hats.pk3
"""
import json
import math
import os
import sys
import zipfile

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "qc_combat_decomp", "bm_hat_tags.qc")


def angles(quat):
    """Quaternion (x, y, z, w) to entity angles for an alias model (the engine negates their pitch)."""
    x, y, z, w = quat
    r00 = 1 - 2 * (y * y + z * z)
    r10 = 2 * (x * y + z * w)
    r20 = 2 * (x * z - y * w)
    r21 = 2 * (y * z + x * w)
    r22 = 1 - 2 * (x * x + y * y)
    pitch = math.asin(max(-1.0, min(1.0, -r20)))
    return (-math.degrees(pitch), math.degrees(math.atan2(r10, r00)), math.degrees(math.atan2(r21, r22)))


def vec(v):
    return "'%.2f %.2f %.2f'" % tuple(v)


def tree(values, lo, hi, pad):
    if hi - lo == 1:
        return "%sreturn %s;\n" % (pad, vec(values[lo]))
    mid = (lo + hi) // 2
    return ("%sif (f < %d)\n%s{\n%s%s}\n" % (pad, mid, pad, tree(values, lo, mid, pad + "\t"), pad)
            + tree(values, mid, hi, pad))


def main():
    with zipfile.ZipFile(sys.argv[1]) as z:
        frames = json.loads(z.read("progs/player_head_tags.json"))["frames"]
    assert [f["frame"] for f in frames] == list(range(len(frames)))
    pos = [f["pos"] for f in frames]
    ang = [angles(f["quat"]) for f in frames]
    with open(OUT, "w", newline="\n") as o:
        o.write("// Generated by source/mm_tools/gen_bm_hat_tags.py from zz_hats.pk3. Do not edit.\n")
        o.write("// Head socket of progs/player_id1.mdl for frames 0..%d.\n\n" % (len(frames) - 1))
        o.write("float BM_HAT_TAG_FRAMES = %d;\n\n" % len(frames))
        for name, values in (("BM_HatTagPos", pos), ("BM_HatTagAng", ang)):
            o.write("vector(float f) %s =\n{\n%s};\n\n" % (name, tree(values, 0, len(values), "\t")))
    print("wrote", os.path.normpath(OUT), len(frames), "frames")


if __name__ == "__main__":
    main()
