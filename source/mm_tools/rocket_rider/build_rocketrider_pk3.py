def _pack_md3_surfaces(surfaces: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Convert surface dicts into md3lib.write() surface structures with sanity checks."""
    md3_surfs = []
    for s in surfaces:
        sname = s["name"]
        shader = s["shader"]
        tris_np = np.asarray(s["tris"], dtype=np.int32)
        uvs_np = np.asarray(s["uvs"], dtype=np.float32)
        frames_in = s["frames"]

        nv = len(uvs_np)
        nt = len(tris_np)
        assert len(frames_in) == C.TOTAL_FRAMES, f"Surface '{sname}' has {len(frames_in)} frames != {C.TOTAL_FRAMES}"
        assert 0 < nv < C.HARD_MD3_VERTS, f"Surface '{sname}' nv={nv} out of bounds"
        assert 0 < nt < C.HARD_MD3_TRIS, f"Surface '{sname}' nt={nt} out of bounds"

        frames_md3 = []
        for fi, fr in enumerate(frames_in):
            if isinstance(fr, tuple):
                vv_np = np.asarray(fr[0], dtype=np.float32)
                nn_np = np.asarray(fr[1], dtype=np.float32)
            else:
                vv_np = np.asarray(fr, dtype=np.float32)
                nn_np = C.compute_vertex_normals(vv_np, tris_np)
            assert vv_np.shape == (nv, 3), f"Surface '{sname}' frame {fi} shape {vv_np.shape} != ({nv}, 3)"
            assert np.isfinite(vv_np).all() and np.isfinite(nn_np).all(), f"NaN/Inf in {sname} frame {fi}"
            max_abs = float(np.max(np.abs(vv_np)))
            assert max_abs < 500.0, f"Surface '{sname}' frame {fi} max |coord|={max_abs:.2f} >= 500u"
            frames_md3.append((vv_np.tolist(), nn_np.tolist()))

        md3_surfs.append(
            {
                "name": sname,
                "shader": shader,
                "tris": tris_np.tolist(),
                "st": uvs_np.tolist(),
                "frames": frames_md3,
            }
        )
    return md3_surfs


def _write_reproducible_pk3(out_pk3: Path, entries: dict[str, bytes]) -> None:
    """Write a deterministic zip/pk3 per AGENTS.md reproducible build rules."""
    out_pk3.parent.mkdir(parents=True, exist_ok=True)
    tmp_pk3 = out_pk3.with_suffix(".pk3.tmp")
    if tmp_pk3.exists():
        tmp_pk3.unlink()

    with zipfile.ZipFile(tmp_pk3, "w") as zf:
        for arcname in sorted(entries.keys()):
            data = entries[arcname]
            ext = Path(arcname).suffix.lower()
            zi = zipfile.ZipInfo(arcname, date_time=(1980, 1, 1, 0, 0, 0))
            zi.create_system = 3
            zi.external_attr = 0o100644 << 16
            if ext in STORE_EXTS:
                zi.compress_type = zipfile.ZIP_STORED
                zf.writestr(zi, data, compress_type=zipfile.ZIP_STORED)
            elif ext in DEFLATE_EXTS:
                zi.compress_type = zipfile.ZIP_DEFLATED
                zf.writestr(zi, data, compress_type=zipfile.ZIP_DEFLATED, compresslevel=6)
            else:
                zi.compress_type = zipfile.ZIP_DEFLATED
                zf.writestr(zi, data, compress_type=zipfile.ZIP_DEFLATED, compresslevel=6)

    os.replace(tmp_pk3, out_pk3)


def _validate_shader_and_skins(
    entries: dict[str, bytes],
    rocket_rt: dict[str, Any],
    rider_rt: dict[str, Any],
) -> None:
    """Assert 100% agreement across MD3 embedded shaders, .skin files, .shader blocks, and PNG maps."""
    assert tuple(sorted(entries.keys())) == tuple(sorted(EXPECTED_ENTRIES)), (
        f"Unexpected entry set: {sorted(entries.keys())} != {sorted(EXPECTED_ENTRIES)}"
    )

    shader_bytes = entries["scripts/rocket_rider.shader"]
    assert b"\r" not in shader_bytes, "scripts/rocket_rider.shader must use LF-only newlines"
    shader_text = shader_bytes.decode("ascii")

    defined_shaders = set(re.findall(r"^(progs/\S+)\s*$", shader_text, re.MULTILINE))
    expected_shaders = {SHADER_ROCKET, SHADER_RANGER, SHADER_FLAME}
    assert defined_shaders == expected_shaders, (
        f"Shader block mismatch: {sorted(defined_shaders)} != {sorted(expected_shaders)}"
    )

    # Check every `map progs/...` PNG exists inside the pk3
    map_refs = re.findall(r"^\s*map\s+(progs/\S+)\s*$", shader_text, re.MULTILINE)
    assert len(map_refs) == 4, f"Expected 4 map directives in shader, found {len(map_refs)}: {map_refs}"
    for mref in map_refs:
        assert mref.endswith(".png"), f"Expected explicit .png map path, got: {mref}"
        assert mref in entries, f"Shader references missing pk3 texture: {mref}"

    # Check MD3 embedded shaders and .md3_0.skin files match 100% identically
    for md3_rt, skin_arc in (
        (rocket_rt, "progs/rocket_rider.md3_0.skin"),
        (rider_rt, "progs/rocket_rider_rider.md3_0.skin"),
    ):
        skin_bytes = entries[skin_arc]
        assert b"\r" not in skin_bytes, f"{skin_arc} must use LF-only newlines"
        skin_lines = [ln.strip() for ln in skin_bytes.decode("ascii").splitlines() if ln.strip()]
        skin_pairs = []
        for ln in skin_lines:
            sname, sh = ln.split(",", 1)
            skin_pairs.append((sname.strip(), sh.strip()))
        md3_pairs = [(s["name"], s["shader"]) for s in md3_rt["surfaces"]]
        assert skin_pairs == md3_pairs, (
            f"{skin_arc} mismatch vs embedded MD3 surfaces: {skin_pairs} != {md3_pairs}"
        )
        for _sname, sh in md3_pairs:
            assert sh in defined_shaders, f"Shader '{sh}' from {skin_arc} missing in scripts/rocket_rider.shader"


def build_zz_rocketrider(
    out_pk3: Path,
    bakersfield_pk3: Path | None = None,
) -> dict[str, Any]:
    """Generate the 2-MD3 V1 Rocket Rider assets in a clean tempdir and pack `out_pk3`."""
    # Prefer repo-committed source/mm_tools/id1/player.mdl (CI-reproducible without bakersfield.pk3),
    # only falling back to bakersfield_pk3 if the repo MDL is absent.
    repo_mdl = C.MM_TOOLS_DIR / "id1" / "player.mdl"
    rig_bakersfield = None if repo_mdl.is_file() else bakersfield_pk3

    with tempfile.TemporaryDirectory(prefix="zz_rocketrider_build_") as td:
        tmp_dir = Path(td)

        # 1. Generate deterministic textures inside TemporaryDirectory
        rocket_tex_p, rocket_glow_p = V1.build_v1_textures(tmp_dir)
        flame_tex_p = C.make_flame_texture(tmp_dir / "rr_v1_flame.png", style="classic", size=512)
        ranger_tex_p = C.ensure_ranger_texture(tmp_dir / "rr_ranger_skin.png")

        # Verify texture sizes & edge/glow invariants
        with Image.open(rocket_tex_p) as im_rocket:
            assert im_rocket.size == (1024, 1024) and im_rocket.mode == "RGB", (
                f"Bad rocket tex: {im_rocket.size} {im_rocket.mode}"
            )
        with Image.open(rocket_glow_p) as im_glow:
            assert im_glow.size == (1024, 1024) and im_glow.mode == "RGB", (
                f"Bad glow tex: {im_glow.size} {im_glow.mode}"
            )
        with Image.open(flame_tex_p) as im_flame:
            assert im_flame.size == (512, 512) and im_flame.mode == "RGB", (
                f"Bad flame tex: {im_flame.size} {im_flame.mode}"
            )
            flame_arr = np.asarray(im_flame)
        with Image.open(ranger_tex_p) as im_ranger:
            assert im_ranger.size == (592, 388) and im_ranger.mode == "RGB", (
                f"Bad ranger tex: {im_ranger.size} {im_ranger.mode}"
            )

        assert (
            flame_arr[:2, :].max() == 0
            and flame_arr[-2:, :].max() == 0
            and flame_arr[:, :2].max() == 0
            and flame_arr[:, -2:].max() == 0
        ), "Flame atlas 2px black border violated!"

        # 2. Build static local-space V1 rocket mesh & canonical Quake 1 Ranger rig
        rb_v, rb_n, rb_u, rb_t = V1.build_v1_rocket_mesh()
        rig = C.QuakeRangerRig(bakersfield_pk3=rig_bakersfield)

        # Locate the exact unique local-space grab-hoop ring vertices centered on GRIP_L and GRIP_R
        # so we can cross-check hoop vs Ranger hands directly between the two round-tripped MD3s!
        def _find_grip_ring_indices(grip_pt: np.ndarray) -> np.ndarray:
            d = np.linalg.norm(rb_v - grip_pt.astype(np.float32), axis=1)
            raw = np.where((d <= 1.50) & (np.abs(rb_v[:, 1] - float(grip_pt[1])) <= 0.25))[0]
            _, uniq_pos = np.unique(np.round(rb_v[raw], 3), axis=0, return_index=True)
            return raw[np.sort(uniq_pos)]

        hoop_l_idx = _find_grip_ring_indices(V1.GRIP_L)
        hoop_r_idx = _find_grip_ring_indices(V1.GRIP_R)
        assert len(hoop_l_idx) >= 8 and len(hoop_r_idx) >= 8, (
            f"Failed to locate U-hoop grip rings in rocket_body: L={len(hoop_l_idx)}, R={len(hoop_r_idx)}"
        )
        assert float(np.linalg.norm(rb_v[hoop_l_idx].mean(axis=0) - V1.GRIP_L)) < 0.01
        assert float(np.linalg.norm(rb_v[hoop_r_idx].mean(axis=0) - V1.GRIP_R)) < 0.01

        # 3. Evaluate all 100 frames using exact V1 transforms & poses
        rocket_frames: list[tuple[np.ndarray, np.ndarray]] = []
        ranger_frames: list[np.ndarray] = []
        flame_nozzles: list[list[dict[str, Any]]] = []
        grip_l_world: list[np.ndarray] = []
        grip_r_world: list[np.ndarray] = []
        frame_names: list[str] = []

        max_hand_err_local = 0.0
        min_ranger_r = 999.0
        min_ranger_vol = 1e18
        max_ranger_edge = 0.0
        e_pairs = np.vstack([rig.tris[:, [0, 1]], rig.tris[:, [1, 2]], rig.tris[:, [2, 0]]])

        for _fi, clip, _k, _u, ph, fname in C.iter_clip_frames():
            frame_names.append(fname)
            params = V1._eval_frame_params(clip["id"], ph)
            veh = params["veh"]
            ofs = np.asarray(veh["offset"], dtype=np.float32)
            pitch = float(veh["pitch_deg"])
            yaw = float(veh["yaw_deg"])
            roll = float(veh["roll_deg"])

            R_v = C.euler_mat(pitch_deg=pitch, yaw_deg=yaw, roll_deg=roll)

            rv = C.apply_vehicle_xform(rb_v, offset=ofs, pitch_deg=pitch, yaw_deg=yaw, roll_deg=roll)
            rn = (rb_n @ R_v.T).astype(np.float32)
            rocket_frames.append((rv, rn))

            r_loc = rig.pose_frame(scale=1.18, **params["rider"])
            lh_err = float(np.linalg.norm(rig.hand_centroid(r_loc, "l_arm") - V1.GRIP_L))
            rh_err = float(np.linalg.norm(rig.hand_centroid(r_loc, "r_arm") - V1.GRIP_R))
            max_hand_err_local = max(max_hand_err_local, lh_err, rh_err)

            in_fuse_x = (r_loc[:, 0] >= -44.0) & (r_loc[:, 0] <= 26.0)
            rad_loc = np.hypot(r_loc[in_fuse_x, 1], r_loc[in_fuse_x, 2])
            min_ranger_r = min(min_ranger_r, float(rad_loc.min()))

            r_vol = C.signed_mesh_volume(r_loc, rig.tris)
            min_ranger_vol = min(min_ranger_vol, r_vol)

            cur_max_e = float(np.linalg.norm(r_loc[e_pairs[:, 0]] - r_loc[e_pairs[:, 1]], axis=1).max())
            max_ranger_edge = max(max_ranger_edge, cur_max_e)

            r_world = C.apply_vehicle_xform(r_loc, offset=ofs, pitch_deg=pitch, yaw_deg=yaw, roll_deg=roll)
            ranger_frames.append(r_world)

            gl_w = C.apply_vehicle_xform(V1.GRIP_L[None, :], offset=ofs, pitch_deg=pitch, yaw_deg=yaw, roll_deg=roll)[0]
            gr_w = C.apply_vehicle_xform(V1.GRIP_R[None, :], offset=ofs, pitch_deg=pitch, yaw_deg=yaw, roll_deg=roll)[0]
            grip_l_world.append(gl_w)
            grip_r_world.append(gr_w)

            noz_org = (V1.NOZZLE_EXIT_LOCAL @ R_v.T) + ofs
            noz_dir = V1.NOZZLE_DIR_LOCAL @ R_v.T
            fl = params["flame"]
            flame_nozzles.append(
                [
                    dict(
                        origin=noz_org,
                        dir=noz_dir,
                        length=fl["length"],
                        radius=fl["radius"],
                        flicker_phase=ph,
                        intensity=fl["intensity"],
                        ribbons_alpha=fl["ribbons_alpha"],
                    )
                ]
            )

        assert max_hand_err_local <= 0.32, f"Local Ranger hand-to-hoop error {max_hand_err_local:.4f}u > 0.32u"
        assert min_ranger_r >= V1.FUSE_RADIUS - 0.05, (
            f"Ranger clips fuselage r={V1.FUSE_RADIUS}u: min_r={min_ranger_r:.2f}u"
        )
        assert min_ranger_vol > 6000.0, f"Ranger signed volume degraded: {min_ranger_vol:.1f}"
        assert max_ranger_edge < 25.0, f"Ranger mesh over-stretched: {max_ranger_edge:.2f}u"

        # 4. Build additive flame surface
        flame_surf = C.make_animated_flame_surface(
            flame_nozzles,
            surface_name="flame_fx",
            shader_name=SHADER_FLAME,
            tex_filename="rr_v1_flame.png",
            n_seg=14,
            n_rings=8,
            n_cards=4,
            n_ribbons=6,
        )

        rocket_surf = {
            "name": "rocket_body",
            "shader": SHADER_ROCKET,
            "tris": rb_t,
            "uvs": rb_u,
            "frames": rocket_frames,
            "additive": 0,
        }
        ranger_surf = {
            "name": "ranger_body",
            "shader": SHADER_RANGER,
            "tris": rig.tris,
            "uvs": rig.uvs,
            "frames": ranger_frames,
            "additive": 0,
        }

        # 5. Apply identical idle_ground (frames 56..67) grounding shift across ALL 3 surfaces
        idle_clip = C.get_clip("idle_ground")
        i0, ic = idle_clip["start"], idle_clip["count"]
        assert i0 == 56 and ic == 12
        dz_idle = C.ground_idle_frames([rocket_surf, ranger_surf, flame_surf], idle_start=i0, idle_count=ic, target_z_min=0.0)
        dz_vec = np.array([0.0, 0.0, dz_idle], dtype=np.float32)
        for fi in range(i0, i0 + ic):
            grip_l_world[fi] = grip_l_world[fi] + dz_vec
            grip_r_world[fi] = grip_r_world[fi] + dz_vec

        # Verify empty rocket_body alone sits flush on Z == 0.00 on idle_ground frames 56..67
        rocket_idle_zmins = [float(rocket_surf["frames"][fi][0][:, 2].min()) for fi in range(i0, i0 + ic)]
        assert abs(min(rocket_idle_zmins)) < 1e-4 and abs(max(rocket_idle_zmins)) < 1e-4, (
            f"Empty rocket idle_ground z_min not flush at 0.00: min={min(rocket_idle_zmins):.5f}, max={max(rocket_idle_zmins):.5f}"
        )

        # Verify exact pre-MD3 world-space lock (same transforms + idle grounding applied to both)
        max_world_pre_md3 = 0.0
        for fi in range(C.TOTAL_FRAMES):
            rg_w = np.asarray(ranger_surf["frames"][fi], dtype=np.float64)
            rv_w = np.asarray(rocket_surf["frames"][fi][0], dtype=np.float64)
            lh_w = rig.hand_centroid(rg_w, "l_arm")
            rh_w = rig.hand_centroid(rg_w, "r_arm")
            hl_w = rv_w[hoop_l_idx].mean(axis=0)
            hr_w = rv_w[hoop_r_idx].mean(axis=0)
            max_world_pre_md3 = max(
                max_world_pre_md3,
                float(np.linalg.norm(lh_w - hl_w)),
                float(np.linalg.norm(rh_w - hr_w)),
            )
        assert max_world_pre_md3 <= 0.32, (
            f"Pre-MD3 world-space Ranger-to-hoop error {max_world_pre_md3:.4f}u > 0.32u"
        )

        # 6. Write the 2 separate MD3 models into TemporaryDirectory
        rocket_md3_path = tmp_dir / "rocket_rider.md3"
        rider_md3_path = tmp_dir / "rocket_rider_rider.md3"

        md3lib.write(
            str(rocket_md3_path),
            {
                "name": "progs/rocket_rider.md3",
                "surfaces": _pack_md3_surfaces([rocket_surf, flame_surf]),
                "frame_names": frame_names,
            },
        )
        md3lib.write(
            str(rider_md3_path),
            {
                "name": "progs/rocket_rider_rider.md3",
                "surfaces": _pack_md3_surfaces([ranger_surf]),
                "frame_names": frame_names,
            },
        )

        # 7. Round-trip verify BOTH MD3s + mathematically prove cross-MD3 hand-to-hoop lock on all 100 frames!
        rocket_rt = md3lib.read(str(rocket_md3_path))
        rider_rt = md3lib.read(str(rider_md3_path))
        assert rocket_rt["nframes"] == C.TOTAL_FRAMES
        assert rider_rt["nframes"] == C.TOTAL_FRAMES
        assert [s["name"] for s in rocket_rt["surfaces"]] == ["rocket_body", "flame_fx"]
        assert [s["name"] for s in rider_rt["surfaces"]] == ["ranger_body"]

        rb_rt_frames = rocket_rt["surfaces"][0]["frames"]
        rg_rt_frames = rider_rt["surfaces"][0]["frames"]

        rt_idle_zmin = min(float(np.asarray(rb_rt_frames[fi][0], dtype=np.float32)[:, 2].min()) for fi in range(i0, i0 + ic))
        assert abs(rt_idle_zmin) <= 0.02, f"Round-trip rocket_rider.md3 idle z_min={rt_idle_zmin:.4f}u != 0.00u"

        max_hand_to_target_rt = 0.0
        max_hoop_to_target_rt = 0.0
        max_cross_md3_err = 0.0
        worst_frame = -1
        for fi in range(C.TOTAL_FRAMES):
            rv_rt = np.asarray(rb_rt_frames[fi][0], dtype=np.float64)
            rg_rt = np.asarray(rg_rt_frames[fi][0], dtype=np.float64)

            lh_rt = rig.hand_centroid(rg_rt, "l_arm")
            rh_rt = rig.hand_centroid(rg_rt, "r_arm")
            hoop_l_rt = rv_rt[hoop_l_idx].mean(axis=0)
            hoop_r_rt = rv_rt[hoop_r_idx].mean(axis=0)

            err_l_tgt = float(np.linalg.norm(lh_rt - grip_l_world[fi]))
            err_r_tgt = float(np.linalg.norm(rh_rt - grip_r_world[fi]))
            max_hand_to_target_rt = max(max_hand_to_target_rt, err_l_tgt, err_r_tgt)

            err_hl_tgt = float(np.linalg.norm(hoop_l_rt - grip_l_world[fi]))
            err_hr_tgt = float(np.linalg.norm(hoop_r_rt - grip_r_world[fi]))
            max_hoop_to_target_rt = max(max_hoop_to_target_rt, err_hl_tgt, err_hr_tgt)

            err_cross_l = float(np.linalg.norm(lh_rt - hoop_l_rt))
            err_cross_r = float(np.linalg.norm(rh_rt - hoop_r_rt))
            cur_cross = max(err_cross_l, err_cross_r)
            if cur_cross > max_cross_md3_err:
                max_cross_md3_err = cur_cross
                worst_frame = fi

        # MD3 int16 vertex quantization is 1/64u (= 0.015625u per axis) on each model
        assert max_hand_to_target_rt <= 0.32, (
            f"Round-trip Ranger hand-to-grip error {max_hand_to_target_rt:.4f}u > 0.32u"
        )
        assert max_hoop_to_target_rt <= 0.02, (
            f"Round-trip rocket U-hoop-to-grip error {max_hoop_to_target_rt:.4f}u > 0.02u"
        )
        assert max_cross_md3_err <= 0.32 + 0.02, (
            f"Cross-MD3 Ranger-to-U-hoop error {max_cross_md3_err:.4f}u > 0.34u (frame {worst_frame})"
        )

        # 8. Assemble all 9 pk3 entries in memory, cross-validate, and write reproducible pk3
        rocket_skin = f"rocket_body,{SHADER_ROCKET}\nflame_fx,{SHADER_FLAME}\n".encode("ascii")
        rider_skin = f"ranger_body,{SHADER_RANGER}\n".encode("ascii")
        shader_bytes = _build_shader_text().encode("ascii")

        entries: dict[str, bytes] = {
            "progs/rocket_rider.md3": rocket_md3_path.read_bytes(),
            "progs/rocket_rider.md3_0.skin": rocket_skin,
            "progs/rocket_rider_rider.md3": rider_md3_path.read_bytes(),
            "progs/rocket_rider_rider.md3_0.skin": rider_skin,
            TEX_ROCKET: rocket_tex_p.read_bytes(),
            TEX_ROCKET_GLOW: rocket_glow_p.read_bytes(),
            TEX_FLAME: flame_tex_p.read_bytes(),
            TEX_RANGER: ranger_tex_p.read_bytes(),
            "scripts/rocket_rider.shader": shader_bytes,
        }

        _validate_shader_and_skins(entries, rocket_rt, rider_rt)
        _write_reproducible_pk3(out_pk3, entries)

    pk3_bytes = out_pk3.read_bytes()
    sha256 = hashlib.sha256(pk3_bytes).hexdigest()
    size = len(pk3_bytes)
    print(
        f"Built {out_pk3}: {len(entries)} entries ({size:,} bytes, sha256={sha256})\n"
        f"  [ground] idle_ground (56..67): dz={dz_idle:+.4f}u -> round-trip z_min={rt_idle_zmin:+.4f}u\n"
        f"  [align]  100f Ranger-to-hoop: exact_world={max_world_pre_md3:.4f}u (<=0.32u), "
        f"rt_hand_vs_grip={max_hand_to_target_rt:.4f}u (<=0.32u), "
        f"rt_hoop_vs_grip={max_hoop_to_target_rt:.4f}u (<=0.02u), "
        f"rt_cross_md3={max_cross_md3_err:.4f}u (frame {worst_frame}: {frame_names[worst_frame]})",
        flush=True,
    )
    return {
        "path": str(out_pk3),
        "size": size,
        "sha256": sha256,
        "entries": sorted(entries.keys()),
        "dz_idle": dz_idle,
        "rt_idle_zmin": rt_idle_zmin,
        "max_hand_err_local": max_hand_err_local,
        "max_world_pre_md3": max_world_pre_md3,
        "max_hand_to_target_rt": max_hand_to_target_rt,
        "max_hoop_to_target_rt": max_hoop_to_target_rt,
        "max_cross_md3_err": max_cross_md3_err,
        "worst_frame": worst_frame,
        "worst_frame_name": frame_names[worst_frame],
    }


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(
        description="Build reproducible zz_rocketrider.pk3 overlay from V1 Classic Quake Munition source."
    )
    parser.add_argument(
        "paths",
        nargs="*",
        help="Optional: [<bakersfield.pk3>] <out_zz_rocketrider.pk3> (zero args writes repo root zz_rocketrider.pk3)",
    )
    parser.add_argument(
        "--check-repro",
        action="store_true",
        help="Build a second copy in a clean tempdir and assert bit-for-bit identical SHA-256.",
    )
    args = parser.parse_args(argv)

    check_repro = bool(args.check_repro)
    bakersfield_pk3: Path | None = None
    if len(args.paths) == 0:
        out_pk3 = DEFAULT_OUT_PK3
    elif len(args.paths) == 1:
        p0 = Path(args.paths[0]).resolve()
        if p0.name.lower() == "bakersfield.pk3":
            bakersfield_pk3 = p0
            out_pk3 = p0.with_name("zz_rocketrider.pk3")
        else:
            out_pk3 = p0
    elif len(args.paths) == 2:
        bakersfield_pk3 = Path(args.paths[0]).resolve()
        out_pk3 = Path(args.paths[1]).resolve()
    else:
        parser.error("Expected at most 2 positional arguments: [<bakersfield.pk3>] <out_zz_rocketrider.pk3>")

    res1 = build_zz_rocketrider(out_pk3, bakersfield_pk3=bakersfield_pk3)
    if check_repro:
        with tempfile.TemporaryDirectory(prefix="zz_rocketrider_repro_") as td:
            check_path = Path(td) / "zz_rocketrider_check.pk3"
            res2 = build_zz_rocketrider(check_path, bakersfield_pk3=bakersfield_pk3)
        assert res1["sha256"] == res2["sha256"], (
            f"Reproducibility check FAILED: {res1['sha256']} != {res2['sha256']}"
        )
        print(f"Reproducibility PASSED: byte-identical SHA-256 = {res1['sha256']}", flush=True)


if __name__ == "__main__":
    main()
