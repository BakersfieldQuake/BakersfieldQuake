#!/usr/bin/env python3
"""Build the reproducible BakersfieldQuake overlay package: zz_rocketrider.pk3.

Never touches bakersfield.pk3 or quake15/q15.pk3, and writes ZERO loose files
into repo `progs/`, `scripts/`, or `source/mm_tools/out/rocket_rider/`.

Uses only Python 3.12 stdlib + pinned numpy==2.5.4 + pillow==13.0.0 (no scipy).
Reuses geometry, textures, Ranger rig, and 100-frame animation transforms directly
from `common.py` and `build_v1_classic.py` to emit the 2-MD3 V1 Classic Quake
Munition runtime package:
  - progs/rocket_rider.md3             (rocket_body + flame_fx, 100 frames, idle grounded at Z=0)
  - progs/rocket_rider.md3_0.skin
  - progs/rocket_rider_rider.md3       (ranger_body only, 100 frames, lockstep sync)
  - progs/rocket_rider_rider.md3_0.skin
  - progs/rr_v1_rocket.png             (1024x1024 weathered ID1 warhead)
  - progs/rr_v1_rocket_glow.png        (1024x1024 molten inner nozzle throat glow)
  - progs/rr_v1_flame.png              (512x512 additive classic flame atlas)
  - progs/rr_ranger_skin.png           (592x388 canonical Quake 1 Ranger palette skin)
  - scripts/rocket_rider.shader        (pure ASCII, LF newlines)

Usage:
    python -I source/mm_tools/rocket_rider/build_rocketrider_pk3.py <bakersfield.pk3> <out_zz_rocketrider.pk3> [--check-repro]
    python -I source/mm_tools/rocket_rider/build_rocketrider_pk3.py [--check-repro]
"""
