"""Appends the 4 Daniel meme videos (v8..v11) to the in-world bk_tv system
(progs/bktv/v8..v11_*.jpg, sound/bklan/tv_8..11.wav, scripts/bktv.shader,
progs/bk_tvscr.md3_<skin>.skin, source/mm_tools/bklan_tv_data.qc)
without disturbing existing clips v0..v7 in staged_assets / bakersfield.pk3.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

CUR_DIR = Path(__file__).resolve().parent
TOOLS_DIR = CUR_DIR.parent
MOD_DIR = TOOLS_DIR.parent.parent
REF_DIR = TOOLS_DIR / "ref" / "daniel"

if str(TOOLS_DIR) not in sys.path:
    sys.path.insert(0, str(TOOLS_DIR))
import md3lib

W, H = 160, 120
FPS = 10
CHUNK = 64
STRIDE = 62
BRIGHT = 0.55

NEW_CLIPS = [
    ("v1_table4am.mp4", "Daniel 4 AM Moving the Table"),
    ("v2_shaaa.mp4",    "Daniel LAN Party SHAAAAA"),
    ("v3_webcam.mp4",   "Daniel Justin Berry Webcam"),
    ("v4_ccc.mp4",      "Daniel CCC Chant"),
]


def ffprobe_dur(path: Path) -> float:
    out = subprocess.check_output(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(path)]
    )
    return float(out.decode().strip())


def main() -> None:
    base_json = TOOLS_DIR / "out" / "bklan_tv_clips.json"
    all_clips = json.loads(base_json.read_text(encoding="utf-8"))[:8]

    fdir = MOD_DIR / "progs" / "bktv"
    sdir = MOD_DIR / "sound" / "bklan"
    fdir.mkdir(parents=True, exist_ok=True)
    sdir.mkdir(parents=True, exist_ok=True)

    # Clean only v8..v11 frames if re-running
    for f in fdir.iterdir():
        if any(f.name.startswith(f"v{v}_") for v in (8, 9, 10, 11)):
            f.unlink()

    for offset, (mp4_name, label) in enumerate(NEW_CLIPS):
        v = 8 + offset
        src = REF_DIR / mp4_name
        dur = ffprobe_dur(src)
        vf = (
            f"fps={FPS},scale={W}:{H}:force_original_aspect_ratio=decrease,"
            f"pad={W}:{H}:(ow-iw)/2:(oh-ih)/2:black,"
            f"eq=brightness=0:contrast=1,lutrgb=r=val*{BRIGHT:.3f}:g=val*{BRIGHT:.3f}:b=val*{BRIGHT:.3f}"
        )
        subprocess.check_call([
            "ffmpeg", "-v", "error", "-y", "-i", str(src), "-an", "-vf", vf,
            "-q:v", "4", "-start_number", "0", str(fdir / f"v{v}_%04d.jpg")
        ])
        n_frames = len([p for p in fdir.iterdir() if p.name.startswith(f"v{v}_")])
        subprocess.check_call([
            "ffmpeg", "-v", "error", "-y", "-i", str(src), "-vn", "-ac", "1", "-ar", "22050",
            "-af", "loudnorm=I=-20:TP=-3", "-c:a", "pcm_s16le", str(sdir / f"tv_{v}.wav")
        ])
        chunks = (n_frames + STRIDE - 1) // STRIDE
        all_clips.append(dict(name=mp4_name, label=label, dur=dur, frames=n_frames, chunks=chunks))
        print(f"TV clip {v} ({label}): {n_frames} frames, {chunks} chunks, {dur:.1f}s")

    shaders = [
        "// generated by build_bklan_tv.py + update_bklan_tv_daniel.py: one shader per 64-frame chunk of the TV clips\n"
        "progs/bktv_off\n{\n\tcull none\n\t{\n\t\tmap progs/bktv_off\n\t\trgbGen identity\n\t}\n}\n"
    ]
    skin = 1
    for v, vd in enumerate(all_clips):
        vd["first"] = skin
        n = vd["frames"]
        for j in range(vd["chunks"]):
            idx = [min(STRIDE * j + i, n - 1) for i in range(CHUNK)]
            names = " ".join(f"progs/bktv/v{v}_{k:04d}" for k in idx)
            shaders.append(
                f"progs/bktv_c{skin}\n{{\n\tcull none\n\t{{\n\t\tanimmap {FPS} {names}\n\t\trgbGen identity\n\t}}\n}}\n"
            )
            skin += 1
    assert skin < 255, f"Too many skins: {skin}"

    (MOD_DIR / "scripts").mkdir(parents=True, exist_ok=True)
    (MOD_DIR / "scripts" / "bktv.shader").write_text("\n".join(shaders), encoding="utf-8")

    # Write skin files for all chunks (0 .. skin-1)
    for k in range(skin):
        sh_name = "off" if k == 0 else f"c{k}"
        (MOD_DIR / "progs" / f"bk_tvscr.md3_{k}.skin").write_text(f"bk_tvscr,progs/bktv_{sh_name}\n", encoding="utf-8")

    # Update bklan_tv_data.qc
    q = [
        "// generated by build_bklan_tv.py + update_bklan_tv_daniel.py: the TV clips (skin of a clip's chunk j = first + j)\n",
        f"float BKTV_CLIPS = {len(all_clips)};\n",
        f"float BKTV_CHUNK = {STRIDE / FPS:.1f};\t\t// seconds a chunk plays ({STRIDE} new frames at {FPS} fps)\n",
        "float(float v) BKTV_First =\n{\n",
    ]
    q += [f"\tif (v == {v}) return {d['first']};\n" for v, d in enumerate(all_clips)]
    q += ["\treturn 1;\n};\n\nfloat(float v) BKTV_Chunks =\n{\n"]
    q += [f"\tif (v == {v}) return {d['chunks']};\n" for v, d in enumerate(all_clips)]
    q += ["\treturn 1;\n};\n\nstring(float v) BKTV_Sound =\n{\n"]
    q += [f'\tif (v == {v}) return "bklan/tv_{v}.wav";\n' for v in range(len(all_clips))]
    q += [
        '\treturn "bklan/tv_0.wav";\n};\n\nvoid() BKTV_Precache =\n{\n'
        "\tif (bktv_precached)\n\t\treturn;\n\tbktv_precached = TRUE;\n"
        '\tprecache_model ("progs/bk_tvscr.md3");\n'
    ]
    q += [f'\tprecache_sound ("bklan/tv_{v}.wav");\n' for v in range(len(all_clips))]
    q += ["};\n"]
    (TOOLS_DIR / "bklan_tv_data.qc").write_text("".join(q), encoding="utf-8")
    base_json.write_text(json.dumps(all_clips, indent=1), encoding="utf-8")
    print(f"Updated bk_tv: {len(all_clips)} total TV clips, {skin - 1} chunk skins")


if __name__ == "__main__":
    main()
