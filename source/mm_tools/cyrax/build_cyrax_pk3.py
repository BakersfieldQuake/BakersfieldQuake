#!/usr/bin/env python3
"""Build the reproducible BakersfieldQuake overlay package: zz_cyrax.pk3.

Never touches bakersfield.pk3 or quake15/q15.pk3!
Uses only Python stdlib + pinned numpy and Pillow + md3lib.

Packages all Cyrax Net Launcher (Slot 10) assets cleanly into zz_cyrax.pk3:
  - progs/v_cyrax.md3                (1-frame 16:9 viewmodel sprite card)
  - progs/v_cyrax.md3_0..55.skin     (56 animation skins: idle, charge, fire, draw, vent)
  - progs/cyrax_vm_00..55.png        (640x390 RGBA, keyed & edge-bled)
  - progs/cyrax_net.md3 (+ _0.skin)  (8-frame pulsing/spinning flying net projectile)
  - progs/cyrax_net.png              (keyed MK3 green net texture)
  - progs/cyrax_wrap.md3 (+ _0.skin) (8-frame pulsing/rotating 3D net cage)
  - progs/cyrax_wrap.png             (seamless tiled MK3 green net cage texture)
  - scripts/cyrax.shader             (LF newlines, nomipmaps + clampmap for VM, crisp alphaFunc GE128 for nets)
  - sound/cyrax/*.wav                (7 deterministic 22050 Hz mono PCM WAVs from assets/sfx/)

Usage:
  python -I source/mm_tools/cyrax/build_cyrax_pk3.py [--out PATH] [--verify-repro]
  python -I source/mm_tools/cyrax/build_cyrax_pk3.py <base_bakersfield.pk3> <out_zz_cyrax.pk3> [--verify-repro]
"""
from __future__ import annotations

import argparse
import hashlib
import os
import struct
import sys
import tempfile
import zipfile
from pathlib import Path
from typing import Dict

HERE = Path(__file__).resolve().parent
MM_TOOLS = HERE.parent
REPO_ROOT = MM_TOOLS.parent.parent
TEX_DIR = HERE / "assets" / "tex"
SFX_DIR = HERE / "assets" / "sfx"
DEFAULT_OUT_PK3 = REPO_ROOT / "zz_cyrax.pk3"

if str(MM_TOOLS) not in sys.path:
    sys.path.insert(0, str(MM_TOOLS))
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

import build_net_models  # noqa: E402
import build_viewmodel  # noqa: E402

FIXED_DATE = (1980, 1, 1, 0, 0, 0)
FILE_ATTR = 0o100644 << 16
STORE_EXTS = {".png", ".jpg", ".jpeg", ".ogg"}

REQUIRED_WAVS = (
    "charge.wav",
    "fire.wav",
    "vent.wav",
    "capture.wav",
    "pull.wav",
    "hold_beep.wav",
    "bonk_launch.wav",
)


def _check_md3(raw: bytes, label: str, expected_frames: int, expected_surfs: list[str]) -> None:
    ident, ver = struct.unpack_from("<4si", raw, 0)
    if ident != b"IDP3" or ver != 15:
        raise ValueError(f"{label}: bad MD3 header {ident!r} v{ver}")
    nframes, _, nsurfs, _, _, _, ofs_surfs, ofs_eof = struct.unpack_from("<8i", raw, 76)
    if nframes != expected_frames or ofs_eof != len(raw):
        raise ValueError(f"{label}: expected {expected_frames} frames & eof {len(raw)}, got {nframes} & {ofs_eof}")
    names: list[str] = []
    cur = ofs_surfs
    for _ in range(nsurfs):
        if raw[cur : cur + 4] != b"IDP3":
            raise ValueError(f"{label}: corrupt surface header")
        names.append(raw[cur + 4 : cur + 68].split(b"\x00", 1)[0].decode("ascii"))
        ofs_end = struct.unpack_from("<i", raw, cur + 104)[0]
        cur += ofs_end
    if names != expected_surfs:
        raise ValueError(f"{label}: surfaces={names!r}, expected {expected_surfs!r}")


def build_shader_text() -> str:
    lines = ["// Generated by source/mm_tools/cyrax/build_cyrax_pk3.py\n"]
    for idx in range(56):
        sh_name = f"progs/cyrax_vm_{idx:02d}"
        lines.append(
            f"{sh_name}\n"
            "{\n"
            "\tcull none\n"
            "\tnomipmaps\n"
            "\t{\n"
            f"\t\tclampmap {sh_name}.png\n"
            "\t\tblendfunc blend\n"
            "\t\trgbGen lightingDiffuse\n"
            "\t}\n"
            "}\n"
        )
    lines.append(
        "progs/cyrax_net\n"
        "{\n"
        "\tcull none\n"
        "\tnomipmaps\n"
        "\t{\n"
        "\t\tclampmap progs/cyrax_net.png\n"
        "\t\talphaFunc GE128\n"
        "\t\tdepthWrite\n"
        "\t\trgbGen identity\n"
        "\t}\n"
        "}\n"
    )
    lines.append(
        "progs/cyrax_wrap\n"
        "{\n"
        "\tcull none\n"
        "\tnomipmaps\n"
        "\t{\n"
        "\t\tmap progs/cyrax_wrap.png\n"
        "\t\talphaFunc GE128\n"
        "\t\tdepthWrite\n"
        "\t\trgbGen wave sin 0.88 0.12 0 2.4\n"
        "\t}\n"
        "}\n"
    )
    return "".join(lines)


def collect_entries() -> Dict[str, bytes]:
    entries: Dict[str, bytes] = {}

    # 1. Viewmodel MD3, 56 skins, and 56 RGBA PNGs
    vm_md3 = build_viewmodel.build_v_cyrax_md3_bytes()
    _check_md3(vm_md3, "v_cyrax", 1, ["card"])
    entries["progs/v_cyrax.md3"] = vm_md3

    for idx in range(56):
        tex_path = TEX_DIR / f"cyrax_vm_{idx:02d}.png"
        if not tex_path.is_file():
            raise FileNotFoundError(f"Missing viewmodel frame texture: {tex_path}")
        sh_name = f"progs/cyrax_vm_{idx:02d}"
        entries[f"{sh_name}.png"] = tex_path.read_bytes()
        entries[f"progs/v_cyrax.md3_{idx}.skin"] = f"card,{sh_name}\n".encode("ascii")

    # 2. Cyrax Net projectile & 3D wrap cage MD3s + textures + skins
    net_md3 = build_net_models.build_cyrax_net_md3_bytes()
    _check_md3(net_md3, "cyrax_net", 8, ["net_sheet_a", "net_sheet_b"])
    entries["progs/cyrax_net.md3"] = net_md3
    entries["progs/cyrax_net.md3_0.skin"] = b"net_sheet_a,progs/cyrax_net\nnet_sheet_b,progs/cyrax_net\n"

    wrap_md3 = build_net_models.build_cyrax_wrap_md3_bytes()
    _check_md3(wrap_md3, "cyrax_wrap", 8, ["wrap_cage"])
    entries["progs/cyrax_wrap.md3"] = wrap_md3
    entries["progs/cyrax_wrap.md3_0.skin"] = b"wrap_cage,progs/cyrax_wrap\n"

    for tname in ("cyrax_net.png", "cyrax_wrap.png"):
        tp = TEX_DIR / tname
        if not tp.is_file():
            raise FileNotFoundError(f"Missing net texture: {tp}")
        entries[f"progs/{tname}"] = tp.read_bytes()

    # 3. Shaders
    entries["scripts/cyrax.shader"] = build_shader_text().encode("ascii")

    # 4. Sounds (from @audio in source/mm_tools/cyrax/assets/sfx/)
    for wav_name in REQUIRED_WAVS:
        wp = SFX_DIR / wav_name
        if not wp.is_file():
            raise FileNotFoundError(f"Missing Cyrax sound asset: {wp}")
        entries[f"sound/cyrax/{wav_name}"] = wp.read_bytes()

    return entries


def write_pk3(out_path: Path, entries: Dict[str, bytes]) -> str:
    out_path.parent.mkdir(parents=True, exist_ok=True)
    tmp_path = out_path.with_suffix(".pk3.tmp")
    if tmp_path.exists():
        tmp_path.unlink()
    with zipfile.ZipFile(tmp_path, "w") as zf:
        for name in sorted(entries):
            info = zipfile.ZipInfo(name, date_time=FIXED_DATE)
            info.create_system = 3
            info.external_attr = FILE_ATTR
            ext = os.path.splitext(name)[1].lower()
            if ext in STORE_EXTS:
                info.compress_type = zipfile.ZIP_STORED
                zf.writestr(info, entries[name])
            else:
                info.compress_type = zipfile.ZIP_DEFLATED
                zf.writestr(info, entries[name], compress_type=zipfile.ZIP_DEFLATED, compresslevel=9)
    tmp_path.replace(out_path)
    return hashlib.sha256(out_path.read_bytes()).hexdigest()


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("pos", nargs="*", help="Optional [base_bakersfield.pk3] <out_pk3>")
    ap.add_argument("--out", type=Path, default=None, help=f"Output pk3 path (default: {DEFAULT_OUT_PK3})")
    ap.add_argument("--verify-repro", "--check-repro", dest="verify_repro", action="store_true",
                    help="Build twice and verify identical SHA-256")
    args = ap.parse_args(argv)

    out_pk3 = args.out
    if out_pk3 is None:
        if len(args.pos) >= 2:
            out_pk3 = Path(args.pos[1])
        elif len(args.pos) == 1:
            out_pk3 = Path(args.pos[0])
        else:
            out_pk3 = DEFAULT_OUT_PK3

    entries = collect_entries()
    sha1 = write_pk3(out_pk3, entries)
    mb = out_pk3.stat().st_size / (1024 * 1024)
    print(f"Built {out_pk3} ({len(entries)} entries, {mb:.2f} MB, sha256={sha1})")

    if args.verify_repro:
        with tempfile.TemporaryDirectory() as td:
            p2 = Path(td) / "zz_cyrax_repro_check.pk3"
            sha2 = write_pk3(p2, collect_entries())
        if sha1 != sha2:
            print(f"ERROR: reproducibility mismatch: {sha1} != {sha2}", file=sys.stderr)
            return 1
        print(f"Reproducibility PASSED: identical sha256 = {sha1}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
